-- Habilitar extensión pgvector para el RAG
CREATE EXTENSION IF NOT EXISTS vector;

-- Tabla especialistas
CREATE TABLE specialists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  specialty TEXT NOT NULL,
  schedule TEXT NOT NULL,
  photo TEXT NOT NULL
);

-- Tabla servicios
CREATE TABLE services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL
);

-- Tabla intermedia especialistas_servicios (Relación N a N)
CREATE TABLE specialist_services (
  specialist_id BIGINT REFERENCES specialists(id) ON DELETE CASCADE,
  service_id BIGINT REFERENCES services(id) ON DELETE CASCADE,
  PRIMARY KEY (specialist_id, service_id)
);

-- Tabla citas (appointments)
CREATE TABLE appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  specialist_id BIGINT REFERENCES specialists(id),
  appointment_date DATE NOT NULL,
  appointment_time TEXT NOT NULL,
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  customer_email TEXT NOT NULL,
  service_name TEXT NOT NULL,
  payment_method TEXT DEFAULT 'Efectivo' NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Tabla para conocimiento base (RAG)
CREATE TABLE knowledge_base (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content TEXT NOT NULL,
  embedding vector(1536) -- asumiendo que se usará text-embedding-ada-002 o text-embedding-3-small de OpenAI
);

