-- ============================================================
-- SEGURIDAD (Row Level Security - RLS)
-- ============================================================

-- 1. Habilitar RLS en todas las tablas
ALTER TABLE specialists ENABLE ROW LEVEL SECURITY;
ALTER TABLE services ENABLE ROW LEVEL SECURITY;
ALTER TABLE specialist_services ENABLE ROW LEVEL SECURITY;
ALTER TABLE appointments ENABLE ROW LEVEL SECURITY;
ALTER TABLE knowledge_base ENABLE ROW LEVEL SECURITY;

-- 2. Políticas para Specialists (Lectura pública para cargar la web)
CREATE POLICY "Permitir lectura pública de especialistas" 
ON specialists FOR SELECT 
TO anon, authenticated 
USING (true);

-- 3. Políticas para Services (Lectura pública para cargar la web)
CREATE POLICY "Permitir lectura pública de servicios" 
ON services FOR SELECT 
TO anon, authenticated 
USING (true);

-- 4. Políticas para specialist_services (Lectura pública de relaciones)
CREATE POLICY "Permitir lectura pública de relaciones" 
ON specialist_services FOR SELECT 
TO anon, authenticated 
USING (true);

-- 5. Políticas para Appointments (Cualquiera puede agendar una cita, pero nadie público puede leer datos de otros)
CREATE POLICY "Permitir inserción pública de citas" 
ON appointments FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- Nota: La tabla 'knowledge_base' no tiene políticas públicas creadas. 
-- Esto significa que está 100% protegida y solo nuestro Backend (usando la service_role key) podrá consultarla.


-- ============================================================
-- FUNCIONES DE SEGURIDAD SECURE RPC
-- ============================================================

-- Función segura para consultar horas ocupadas sin exponer nombres, correos o teléfonos de clientes
CREATE OR REPLACE FUNCTION get_booked_times(p_specialist_id BIGINT, p_date DATE)
RETURNS TABLE (appointment_time TEXT) 
SECURITY DEFINER -- Ejecuta con permisos del creador, evadiendo RLS de forma segura
AS $$
BEGIN
  RETURN QUERY
  SELECT a.appointment_time 
  FROM appointments a
  WHERE a.specialist_id = p_specialist_id 
    AND a.appointment_date = p_date;
END;
$$ LANGUAGE plpgsql;


